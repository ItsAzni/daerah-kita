/** 405 nilai resmi BPS Jawa Barat (2025/2026), tanpa nilai kosong. */
export const INDICATOR_VALUES: IndicatorValue[] = REGIONS.flatMap((region) => {
  const row = VALUE_TABLE[region.code] ?? []
  return INDICATORS.map((indicator, index) => ({
    id: `${region.code}-${indicator.code}`,
    region_id: region.code,
    indicator_id: indicator.code,
    value: row[index] ?? Number.NaN,
    period: indicator.period,
  }))
})

export const VALUE_INDEX: Map<string, number> = new Map(
  INDICATOR_VALUES.map((entry) => [
    `${entry.region_id}:${entry.indicator_id}`,
    entry.value,
  ])
)

export function getValue(
  regionCode: string,
  indicatorCode: string
): number | undefined {
  return VALUE_INDEX.get(`${regionCode}:${indicatorCode}`)
}
